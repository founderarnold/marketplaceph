// Writes supabase/seeds/jobs_starter_posts.sql from scripts/starter-jobs.mjs.
// Usage: node scripts/build-starter-jobs-seed.mjs
// The SQL is NOT run automatically (it is not in supabase/migrations and not in config.toml sql_paths).
import { writeFileSync } from "node:fs";
import { EMPLOYERS, JOBS, descriptionOf, qualificationsOf } from "./starter-jobs.mjs";

const q = (s) => (s == null ? "null" : `'${String(s).replaceAll("'", "''")}'`);

const employerRows = Object.entries(EMPLOYERS)
  .map(([key, e]) => `    (${q(key)}, ${q(e.company)}, array[${e.storeLike.map(q).join(", ")}]::text[], null::uuid)`)
  .join(",\n");

const jobRows = JOBS.map((j) =>
  `    (${q(j.key)}, ${q(j.employer)}, ${q(j.title)}, ${q(j.category)}, ${q(j.employment_type)}, ${q(j.work_setup)}, ${j.vacancies ?? 1},\n` +
  `     ${q(descriptionOf(j))},\n     ${q(qualificationsOf(j))})`,
).join(",\n");

const sql = `-- MarketplacePH starter job posts (generated by scripts/build-starter-jobs-seed.mjs; edit scripts/starter-jobs.mjs instead).
--
-- WHAT IT DOES: inserts ${JOBS.length} job posts as HIDDEN drafts (status = 'hidden') under the employer accounts below.
--   Hidden posts are not shown on /jobs. An admin fills in pay and location in Admin → Jobs → Edit, then publishes.
--   Publishing is blocked while any "[ADMIN TO FILL" placeholder is left in the text.
-- IDEMPOTENT: a post is skipped if the same owner already has a post with the same title and company (any status).
-- SAFE: inserts only; never updates or deletes existing rows. Employers that cannot be found are skipped with a NOTICE.
--
-- HOW TO RUN (owner decision; do NOT run on production without approval and a backup):
--   1. Check each employer is found: run only the "preview" query at the bottom first.
--   2. If an employer's store name differs, set its owner_id in the employers list (profile id of the employer account).
--   3. Run the whole file in the Supabase SQL editor (staging first).

begin;

create temporary table starter_employers (employer_key text primary key, company_name text not null, store_like text[] not null, owner_id uuid) on commit drop;
insert into starter_employers (employer_key, company_name, store_like, owner_id) values
${employerRows};

-- Fill owner_id from the oldest store whose name matches, unless it was set above.
update starter_employers e set owner_id = (
  select s.owner_id from public.stores s
  where exists (select 1 from unnest(e.store_like) p where s.name ilike p or s.slug ilike replace(p, ' ', '-'))
  order by s.created_at asc limit 1)
where e.owner_id is null;

do $$
declare r record;
begin
  for r in select employer_key, company_name from starter_employers where owner_id is null loop
    raise notice 'Starter jobs: no account found for % (%); its posts are skipped. Set owner_id and re-run.', r.company_name, r.employer_key;
  end loop;
end $$;

create temporary table starter_jobs (job_key text primary key, employer_key text not null, title text not null, category text not null,
  employment_type text not null, work_setup text not null, vacancies int not null, description text not null, qualifications text not null) on commit drop;
insert into starter_jobs values
${jobRows};

insert into public.job_posts (owner_id, poster_type, company_name, title, category, description, qualifications, employment_type, work_setup, vacancies, status)
select e.owner_id, 'employer', e.company_name, j.title, j.category, j.description, j.qualifications, j.employment_type, j.work_setup, j.vacancies, 'hidden'
from starter_jobs j
join starter_employers e on e.employer_key = j.employer_key
where e.owner_id is not null
  and not exists (select 1 from public.job_posts p where p.owner_id = e.owner_id and p.title = j.title and p.company_name = e.company_name);

-- Preview: which employer accounts were found and how many starter posts each now has.
select e.employer_key, e.company_name, e.owner_id is not null as account_found,
  (select count(*) from public.job_posts p join starter_jobs j on j.title = p.title and j.employer_key = e.employer_key
    where p.owner_id = e.owner_id and p.company_name = e.company_name) as starter_posts
from starter_employers e order by 1;

commit;
`;

writeFileSync(new URL("../supabase/seeds/jobs_starter_posts.sql", import.meta.url), sql);
console.log(`Wrote ${JOBS.length} starter posts to supabase/seeds/jobs_starter_posts.sql`);
